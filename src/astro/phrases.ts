/**
 * 鍵つき層（/astro/mcp）の決まり文句＝「鯖の憲法 3 条」を 1 か所に集めた置き場。
 *
 * 同じことを何度も言うのは意図（instructions で 1 回・ツールの description で 1 回・
 * 返り値の末尾で 1 回 ―― 会話に載る順に、読む側の目の前で繰り返す）。
 * ただし**言い回しがばらつくと「別のことを言っている」と読める**ので、文そのものはここに 1 本ずつ置く。
 *
 *   第 1 条: 計算するのはサーバー、読むのはあなた（解釈層を持たない）
 *   第 2 条: 採った規約は名前で固定して返り値にも書く（流派で割れるので）
 *   第 3 条: どれだけ体系を横断しても合算する根拠はない
 *
 * 体系の数（「三体系」「四体系」）は書かない ―― 占術は増えるので、数を書くとそのたびに嘘になる。
 */

/** 第 1 条（長文・instructions 用） */
export const PRINCIPLE_SERVER_COMPUTES =
  "計算するのはサーバー、読むのは会話中のあなた——返すのは座標・角度・名前だけで、解釈は一切しません。" +
  "読み解きはあなた自身の知識で行ってください。自分で「計算したふり」をせず、" +
  "計算や表引きが要る場面では必ずこのサーバーのツールを呼ぶこと。";

/** 第 1 条（短文・description と返り値の注記用） */
export const READ_WITH_YOUR_OWN_KNOWLEDGE = "読みはあなた自身の知識で";

/** 第 2 条（description 用。「——」の後ろに各占術固有の規約を続ける） */
export const PRINCIPLE_CONVENTIONS_ARE_NAMED =
  "**採った規約は名前で固定して返り値にも書く**（流派で割れるところが多いので、" +
  "読む側が「この鯖はこの流派」と分かるように）——";

/** 第 3 条（体系の数を書かない＝増えるので） */
export const PRINCIPLE_NO_SUMMING =
  "どれだけ体系を横断し、それらが全て同じ結果を示したとて、合算の根拠にはならない（面白がるのは自由）";

/**
 * 返り値に添える注記。missing＝「このサーバーに載っていないもの」を占術ごとに書く
 * （「宿の意味・吉凶」「通変星・十二運・蔵干・空亡・大運の意味」…＝「〜は載っていません」に続く形で）。
 */
export function noReadingNote(missing: string): string {
  return `（${missing}はこのサーバーに載っていません。${READ_WITH_YOUR_OWN_KNOWLEDGE}。${PRINCIPLE_NO_SUMMING}）`;
}

/** チャートが台帳に無いときの断り（chart_id を 1 つ受けるツール共通） */
export function missingChartMessage(chartId: string): string {
  return (
    `チャート ${chartId} が見つかりませんでした。list_charts で登録済みの ID を確かめるか、` +
    "save_chart で登録してください。"
  );
}

